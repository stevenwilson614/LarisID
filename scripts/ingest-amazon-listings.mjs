#!/usr/bin/env node
/**
 * Upsert LarisExpor Amazon keywords + listings into Contabo Postgres.
 *
 * Reads:
 *   scripts/expor-keywords.json
 *   scripts/expor-amazon-listings.json  (from fetch-dataforseo-amazon.mjs
 *                                        or the Amazon US SERP seed)
 *
 * Apply:
 *   node scripts/ingest-amazon-listings.mjs --apply
 *
 * Never invents prices or bought_past_month. Writes SQL and pipes it through
 * scripts/apply-selfhost.sh (ssh + docker psql). Do not use supabase db push.
 */
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const KEYWORDS = path.join(__dirname, 'expor-keywords.json');
const LISTINGS = path.join(__dirname, 'expor-amazon-listings.json');
const APPLY = process.argv.includes('--apply');

function lit(v) {
  if (v == null || v === '') return 'NULL';
  if (typeof v === 'boolean') return v ? 'TRUE' : 'FALSE';
  if (typeof v === 'number') {
    if (!Number.isFinite(v)) return 'NULL';
    return String(v);
  }
  return `'${String(v).replace(/'/g, "''")}'`;
}

function ts(v) {
  if (!v) return 'now()';
  return lit(String(v));
}

const corpus = JSON.parse(fs.readFileSync(KEYWORDS, 'utf8'));
const listingFile = fs.existsSync(LISTINGS)
  ? JSON.parse(fs.readFileSync(LISTINGS, 'utf8'))
  : { listings: [] };
const listings = Array.isArray(listingFile.listings) ? listingFile.listings : [];
const kws = corpus.keywords || [];
if (!kws.length) {
  process.stderr.write('FATAL: no keywords in expor-keywords.json\n');
  process.exit(1);
}

const kwRows = kws.map((p) => `(${[
  lit(p.slug),
  lit(p.kw),
  lit(p.nama),
  lit(p.kategori),
  lit(p.hs || null),
  lit(p.wilayah || null),
].join(', ')})`);

const listingRows = listings.filter((r) => r && r.asin && r.keyword).map((r) => `(${[
  lit(r.asin),
  lit(r.keyword),
  lit(r.slug || null),
  lit(r.title || null),
  lit(r.image_url || null),
  lit(r.url || (r.asin ? `https://www.amazon.com/dp/${r.asin}` : null)),
  r.price_usd == null ? 'NULL' : lit(Number(r.price_usd)),
  r.rating == null ? 'NULL' : lit(Number(r.rating)),
  r.reviews == null ? 'NULL' : lit(Number(r.reviews)),
  r.bought_past_month == null ? 'NULL' : lit(Number(r.bought_past_month)),
  lit(!!r.is_amazon_choice),
  lit(!!r.is_best_seller),
  r.search_rank == null && r.rank == null ? 'NULL' : lit(Number(r.search_rank ?? r.rank)),
  ts(r.fetched_at),
].join(', ')})`);

const snapRows = listings.filter((r) => r && r.asin && r.keyword).map((r) => `(${[
  lit(r.asin),
  lit(r.keyword),
  ts(r.fetched_at),
  r.price_usd == null ? 'NULL' : lit(Number(r.price_usd)),
  r.rating == null ? 'NULL' : lit(Number(r.rating)),
  r.reviews == null ? 'NULL' : lit(Number(r.reviews)),
  r.bought_past_month == null ? 'NULL' : lit(Number(r.bought_past_month)),
  r.search_rank == null && r.rank == null ? 'NULL' : lit(Number(r.search_rank ?? r.rank)),
].join(', ')})`);

const sql = `-- generated by scripts/ingest-amazon-listings.mjs
begin;

insert into public.amazon_keywords (slug, kw_en, nama_id, kategori, hs, wilayah)
values
${kwRows.join(',\n')}
on conflict (slug) do update set
  kw_en = excluded.kw_en,
  nama_id = excluded.nama_id,
  kategori = excluded.kategori,
  hs = excluded.hs,
  wilayah = excluded.wilayah,
  updated_at = now();

${listingRows.length ? `insert into public.amazon_listings (
  asin, keyword, slug, title, image_url, url,
  price_usd, rating, reviews, bought_past_month,
  is_amazon_choice, is_best_seller, search_rank, fetched_at
) values
${listingRows.join(',\n')}
on conflict (asin, keyword) do update set
  slug = excluded.slug,
  title = excluded.title,
  image_url = excluded.image_url,
  url = excluded.url,
  price_usd = excluded.price_usd,
  rating = excluded.rating,
  reviews = excluded.reviews,
  bought_past_month = excluded.bought_past_month,
  is_amazon_choice = excluded.is_amazon_choice,
  is_best_seller = excluded.is_best_seller,
  search_rank = excluded.search_rank,
  fetched_at = excluded.fetched_at;` : '-- no listings to upsert'}

${snapRows.length ? `insert into public.amazon_listing_snapshots (
  asin, keyword, fetched_at, price_usd, rating, reviews, bought_past_month, search_rank
) values
${snapRows.join(',\n')}
on conflict (asin, keyword, fetched_at) do update set
  price_usd = excluded.price_usd,
  rating = excluded.rating,
  reviews = excluded.reviews,
  bought_past_month = excluded.bought_past_month,
  search_rank = excluded.search_rank;` : ''}

notify pgrst, 'reload schema';
commit;
`;

const sqlPath = path.join(__dirname, '_amazon_ingest.sql');
fs.writeFileSync(sqlPath, sql);
process.stderr.write(
  `Wrote ${path.relative(ROOT, sqlPath)} (${kws.length} keywords, ${listingRows.length} listings)\n`,
);

if (!APPLY) {
  process.stderr.write('Dry run. Re-run with --apply to push to Contabo.\n');
  process.exit(0);
}

const r = spawnSync('bash', [path.join(ROOT, 'scripts/apply-selfhost.sh'), sqlPath], {
  stdio: 'inherit',
  cwd: ROOT,
});
process.exit(r.status || 0);
